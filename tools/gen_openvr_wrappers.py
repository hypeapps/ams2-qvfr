"""Generates the OpenVR 0.9.12 interface wrappers and the export thunks of the proxy.

Input:   third_party/openvr-0.9.12/headers/openvr.h, exports of third_party/openvr-0.9.12/bin/win64/openvr_api.dll
Output:  src/proxy/generated/wrappers_0912.h, src/proxy/generated/exports.inc, src/proxy/generated/thunks.asm

Each wrapper derives from the interface in the 0.9.12 header and forwards every method to the real object,
counting calls. `override` makes the compiler check signatures and method order against the header.
Methods the proxy handles itself are overridden by a hand-written derived class (src/proxy/wrappers.cpp).

Run from the repo root: python tools/gen_openvr_wrappers.py
"""

import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / "third_party/openvr-0.9.12/headers/openvr.h"
CAPI = ROOT / "third_party/openvr-0.9.12/headers/openvr_capi.h"
DLL = ROOT / "third_party/openvr-0.9.12/bin/win64/openvr_api.dll"
OUT_H = ROOT / "src/proxy/generated/wrappers_0912.h"
OUT_EXP = ROOT / "src/proxy/generated/exports.inc"
OUT_ASM = ROOT / "src/proxy/generated/thunks.asm"

# Interfaces used by AMS2 (IVRSystem from VR_Init, VRCompositor and VROverlay from the exports).
INTERFACES = [
    ("IVRSystem", "System", "IVRSystem_009"),
    ("IVRCompositor", "Compositor", "IVRCompositor_009"),
    ("IVROverlay", "Overlay", "IVROverlay_007"),
]

# Exports the proxy implements itself (src/proxy/exports.cpp). The rest are thunks to the backend.
OWN_EXPORTS = {
    "VR_Init", "VR_Shutdown", "VR_IsHmdPresent", "VR_IsRuntimeInstalled",
    "VR_GetGenericInterface", "VR_GetVRInitErrorAsEnglishDescription", "VR_GetVRInitErrorAsSymbol",
    "VR_GetStringForHmdError", "VRSystem", "VRCompositor", "VROverlay",
}



def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def class_body(text: str, name: str) -> str:
    m = re.search(r"\bclass\s+" + name + r"\s*\{", text)
    if not m:
        sys.exit(f"class {name} not found")
    depth, i = 1, m.end()
    while depth:
        c = text[i]
        depth += c == "{"
        depth -= c == "}"
        i += 1
    return text[m.end():i - 1]


def split_params(s: str):
    out, depth, cur = [], 0, ""
    for c in s:
        if c == "," and depth == 0:
            out.append(cur)
            cur = ""
            continue
        depth += c == "("
        depth -= c == ")"
        cur += c
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out]


def parse_methods(body: str):
    methods = []
    for m in re.finditer(r"virtual\s+(.+?)\s*=\s*0\s*;", body, flags=re.S):
        decl = " ".join(m.group(1).split())
        # Annotation macros from the header (they expand to nothing).
        decl = re.sub(r"\bVR_(ARRAY_COUNT|OUT_STRING|OUT_STRING_COUNT|OUT_ARRAY_CALL|OUT_ARRAY_COUNT|OUT_BUFFER_COUNT|"
                      r"OUT_STRUCT|ARRAY_COUNT_D|CLANG_ATTR)\s*\([^)]*\)\s*", "", decl)
        mm = re.match(r"(.+?)\s*\b(\w+)\s*\((.*)\)\s*(const)?$", decl)
        if not mm:
            sys.exit(f"cannot parse: {decl}")
        ret, name, params, const = mm.group(1).strip(), mm.group(2), mm.group(3).strip(), mm.group(4)
        plist = []
        if params and params != "void":
            for p in split_params(params):
                p = re.sub(r"\s*=\s*.+$", "", p)  # default arguments
                pm = re.match(r"(.+?)\s*\b(\w+)$", p)
                if not pm:
                    sys.exit(f"unnamed parameter in {name}: {p}")
                plist.append((pm.group(1).strip(), pm.group(2)))
        methods.append((ret, name, plist, const))
    return methods


def pe_exports(path: pathlib.Path):
    data = path.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    opt = pe + 24
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    exp_rva = struct.unpack_from("<I", data, opt + 112)[0]  # PE32+: export directory
    secs = []
    for i in range(nsec):
        s = pe + 24 + opt_size + i * 40
        vsize, va, rsize, raw = struct.unpack_from("<IIII", data, s + 8)
        secs.append((va, max(vsize, rsize), raw))

    def off(rva):
        for va, size, raw in secs:
            if va <= rva < va + size:
                return rva - va + raw
        raise ValueError(rva)

    e = off(exp_rva)
    n_names = struct.unpack_from("<I", data, e + 24)[0]  # NumberOfNames
    names_rva = struct.unpack_from("<I", data, e + 32)[0]  # AddressOfNames
    names = []
    for i in range(n_names):
        r = struct.unpack_from("<I", data, off(names_rva) + 4 * i)[0]
        o = off(r)
        names.append(data[o:data.index(b"\0", o)].decode())
    return names


def gen_header(text: str) -> str:
    lines = [
        "// GENERATED by tools/gen_openvr_wrappers.py from third_party/openvr-0.9.12/headers/openvr.h. Do not edit by hand.",
        "#pragma once",
        "",
        "// Requires openvr.h 0.9.12 to be included first, and the declaration:",
        "//   void qvfr::TraceCall(int iface, int method);",
        "",
        "namespace qvfr { void TraceCall(int iface, int method); }",
        "",
        "namespace vr {",
        "namespace gen {",
        "",
    ]
    for idx, (cls, short, version) in enumerate(INTERFACES):
        methods = parse_methods(class_body(text, cls))
        lines.append(f"constexpr int k{short}Iface = {idx};")
        lines.append(f"constexpr int k{short}MethodCount = {len(methods)};")
        lines.append(f"inline const char* const k{short}Version = \"{version}\";")
        lines.append(f"inline const char* const k{short}MethodNames[] = {{")
        for _, name, _, _ in methods:
            lines.append(f"    \"{name}\",")
        lines.append("};")
        lines.append("")
        lines.append(f"class {short}WrapBase : public {cls} {{")
        lines.append("public:")
        lines.append(f"    explicit {short}WrapBase({cls}* real) : real_(real) {{}}")
        lines.append(f"    {cls}* Real() const {{ return real_; }}")
        lines.append("")
        for mi, (ret, name, plist, const) in enumerate(methods):
            sig = ", ".join(f"{t} {n}" for t, n in plist)
            args = ", ".join(n for _, n in plist)
            c = " const" if const else ""
            ret_kw = "" if ret == "void" else "return "
            lines.append(f"    {ret} {name}({sig}){c} override {{ qvfr::TraceCall({idx}, {mi}); "
                         f"{ret_kw}real_->{name}({args}); }}")
        lines.append("")
        lines.append("protected:")
        lines.append(f"    {cls}* real_;")
        lines.append("};")
        lines.append("")
    lines.append("constexpr int kIfaceCount = %d;" % len(INTERFACES))
    lines.append("")
    lines.append("}  // namespace gen")
    lines.append("}  // namespace vr")
    lines.append("")
    return "\n".join(lines)


def thunked(exports):
    missing = OWN_EXPORTS - set(exports)
    if missing:
        sys.exit(f"OWN_EXPORTS not present in the original: {missing}")
    return [name for name in exports if name not in OWN_EXPORTS]


def struct_returns() -> dict:
    # Flat functions that return a struct by value (openvr_capi.h): the caller passes a hidden pointer in rcx and expects
    # it back in rax, so the stand-in for an export the backend lacks must zero that struct and return the pointer.
    text = CAPI.read_text(encoding="utf-8", errors="replace")
    return dict((m.group(2), m.group(1)) for m in re.finditer(r"^S_API struct (\w+) (VR_\w+)\(", text, re.M))


def gen_exports_inc(names) -> str:
    # Each export the proxy does not implement is a thunk (thunks.asm) that jumps through qvfr_thunk_table to the same
    # export of the backend chosen at run time ([runtime] path), instead of a forwarder bound to one module name.
    lines = [
        "// GENERATED by tools/gen_openvr_wrappers.py from the exports of openvr_api.dll 0.9.12. Do not edit by hand.",
        "// Functions in OWN_EXPORTS are exported by the proxy code (__declspec(dllexport)); the rest are thunks",
        "// (thunks.asm) to the backend's export of the same name.",
    ]
    for i, name in enumerate(names):
        lines.append(f'#pragma comment(linker, "/EXPORT:{name}=qvfr_thunk_{i}")')
    lines.append("")
    lines.append(f"constexpr unsigned kThunkCount = {len(names)};")
    lines.append("const char* const kThunkNames[kThunkCount] = {")
    for name in names:
        lines.append(f'    "{name}",')
    lines.append("};")
    structs = struct_returns()
    lines.append("// Stand-in for an export the backend does not have: MissingZero returns 0, MissingStruct<N> zeroes the")
    lines.append("// returned struct (hidden pointer) and returns its address.")
    lines.append("void* const kThunkMissing[kThunkCount] = {")
    for name in names:
        t = structs.get(name)
        lines.append(f"    reinterpret_cast<void*>(&MissingStruct<sizeof(vr::{t})>)," if t else
                     "    reinterpret_cast<void*>(&MissingZero),")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def gen_thunks_asm(names) -> str:
    # qvfr_thunk_i jumps through slot i. A slot starts at lazy_i, which passes i to qvfr_lazy_common: that saves the
    # argument registers, calls qvfr_ResolveThunk(i) (C++, loads the backend, fills the slot) and jumps to the result.
    n = len(names)
    out = [
        "; GENERATED by tools/gen_openvr_wrappers.py. Do not edit by hand.",
        "; Export thunks of the openvr_api.dll proxy (x64 MASM), see exports.inc.",
        "",
        "EXTERN qvfr_ResolveThunk:PROC",
        "",
        ".data",
        "PUBLIC qvfr_thunk_table",
        "ALIGN 8",
        "qvfr_thunk_table LABEL QWORD",
    ]
    out += [f"    QWORD lazy_{i}" for i in range(n)]
    out += ["", ".code", ""]
    for i in range(n):
        out += [f"qvfr_thunk_{i} PROC", f"    jmp QWORD PTR [qvfr_thunk_table + {8 * i}]", f"qvfr_thunk_{i} ENDP"]
    out.append("")
    # The slot index travels in eax: rax is volatile and carries no argument in the Windows x64 convention.
    for i in range(n):
        out += [f"lazy_{i} PROC", f"    mov eax, {i}", "    jmp qvfr_lazy_common", f"lazy_{i} ENDP"]
    out += [
        "",
        "; Entry: rsp = 8 mod 16 (return address of the original call at [rsp]). After sub 0A8h the return address is at",
        "; [rsp + 0A8h] and the caller's home area for rcx, rdx, r8, r9 at [rsp + 0B0h .. 0C8h]; xmm0-xmm3 go to our frame",
        "; (16-byte aligned), [rsp .. 1Fh] is the home area for the call to qvfr_ResolveThunk.",
        "qvfr_lazy_common PROC FRAME",
        "    sub rsp, 0A8h",
        "    .allocstack 0A8h",
        "    .endprolog",
        "    mov QWORD PTR [rsp + 0B0h], rcx",
        "    mov QWORD PTR [rsp + 0B8h], rdx",
        "    mov QWORD PTR [rsp + 0C0h], r8",
        "    mov QWORD PTR [rsp + 0C8h], r9",
        "    movdqa XMMWORD PTR [rsp + 20h], xmm0",
        "    movdqa XMMWORD PTR [rsp + 30h], xmm1",
        "    movdqa XMMWORD PTR [rsp + 40h], xmm2",
        "    movdqa XMMWORD PTR [rsp + 50h], xmm3",
        "    mov ecx, eax",
        "    call qvfr_ResolveThunk",
        "    movdqa xmm0, XMMWORD PTR [rsp + 20h]",
        "    movdqa xmm1, XMMWORD PTR [rsp + 30h]",
        "    movdqa xmm2, XMMWORD PTR [rsp + 40h]",
        "    movdqa xmm3, XMMWORD PTR [rsp + 50h]",
        "    mov rcx, QWORD PTR [rsp + 0B0h]",
        "    mov rdx, QWORD PTR [rsp + 0B8h]",
        "    mov r8, QWORD PTR [rsp + 0C0h]",
        "    mov r9, QWORD PTR [rsp + 0C8h]",
        "    add rsp, 0A8h",
        "    jmp rax",
        "qvfr_lazy_common ENDP",
        "",
        "END",
        "",
    ]
    return "\n".join(out)


def main():
    text = strip_comments(HEADER.read_text(encoding="utf-8", errors="replace"))
    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(gen_header(text), encoding="utf-8", newline="\n")
    exports = pe_exports(DLL)
    names = thunked(exports)
    OUT_EXP.write_text(gen_exports_inc(names), encoding="utf-8", newline="\n")
    OUT_ASM.write_text(gen_thunks_asm(names), encoding="utf-8", newline="\n")
    print(f"{OUT_H.relative_to(ROOT)}: {len(INTERFACES)} interfaces")
    print(f"{OUT_EXP.relative_to(ROOT)}, {OUT_ASM.relative_to(ROOT)}: {len(exports)} exports, {len(names)} thunks")


if __name__ == "__main__":
    main()
