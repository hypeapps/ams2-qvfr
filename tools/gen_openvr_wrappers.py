"""Generates the OpenVR 0.9.12 interface wrappers and the list of forwarded proxy exports.

Input:   third_party/openvr-0.9.12/headers/openvr.h, exports of third_party/openvr-0.9.12/bin/win64/openvr_api.dll
Output:  src/proxy/generated/wrappers_0912.h, src/proxy/generated/forwards.inc

Each wrapper derives from the interface in the 0.9.12 header and forwards every method to the real object,
counting calls. `override` makes the compiler check signatures and method order against the header.
Methods the proxy handles itself are overridden by a hand-written derived class (src/proxy/wrappers.cpp).

Run from the repo root: python tools/gen_openvr_wrappers.py
"""

import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / "third_party/openvr-0.9.12/headers/openvr.h"
DLL = ROOT / "third_party/openvr-0.9.12/bin/win64/openvr_api.dll"
OUT_H = ROOT / "src/proxy/generated/wrappers_0912.h"
OUT_FWD = ROOT / "src/proxy/generated/forwards.inc"

# Interfaces used by AMS2 (IVRSystem from VR_Init, VRCompositor and VROverlay from the exports).
INTERFACES = [
    ("IVRSystem", "System", "IVRSystem_009"),
    ("IVRCompositor", "Compositor", "IVRCompositor_009"),
    ("IVROverlay", "Overlay", "IVROverlay_007"),
]

# Exports the proxy implements itself (src/proxy/exports.cpp). The rest are forwarded to the original.
OWN_EXPORTS = {
    "VR_Init", "VR_Shutdown", "VR_IsHmdPresent", "VR_IsRuntimeInstalled",
    "VR_GetGenericInterface", "VR_GetVRInitErrorAsEnglishDescription", "VR_GetVRInitErrorAsSymbol",
    "VR_GetStringForHmdError", "VRSystem", "VRCompositor", "VROverlay",
}
ORIG_MODULE = "openvr_api_orig"


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def class_body(text: str, name: str) -> str:
    m = re.search(r"\bclass\s+" + name + r"\s*\{", text)
    if not m:
        sys.exit(f"class {name} not found")
    depth, i = 1, m.end()
    while depth:
        c = text[i]
        depth += c == "{"
        depth -= c == "}"
        i += 1
    return text[m.end():i - 1]


def split_params(s: str):
    out, depth, cur = [], 0, ""
    for c in s:
        if c == "," and depth == 0:
            out.append(cur)
            cur = ""
            continue
        depth += c == "("
        depth -= c == ")"
        cur += c
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out]


def parse_methods(body: str):
    methods = []
    for m in re.finditer(r"virtual\s+(.+?)\s*=\s*0\s*;", body, flags=re.S):
        decl = " ".join(m.group(1).split())
        # Annotation macros from the header (they expand to nothing).
        decl = re.sub(r"\bVR_(ARRAY_COUNT|OUT_STRING|OUT_STRING_COUNT|OUT_ARRAY_CALL|OUT_ARRAY_COUNT|OUT_BUFFER_COUNT|"
                      r"OUT_STRUCT|ARRAY_COUNT_D|CLANG_ATTR)\s*\([^)]*\)\s*", "", decl)
        mm = re.match(r"(.+?)\s*\b(\w+)\s*\((.*)\)\s*(const)?$", decl)
        if not mm:
            sys.exit(f"cannot parse: {decl}")
        ret, name, params, const = mm.group(1).strip(), mm.group(2), mm.group(3).strip(), mm.group(4)
        plist = []
        if params and params != "void":
            for p in split_params(params):
                p = re.sub(r"\s*=\s*.+$", "", p)  # default arguments
                pm = re.match(r"(.+?)\s*\b(\w+)$", p)
                if not pm:
                    sys.exit(f"unnamed parameter in {name}: {p}")
                plist.append((pm.group(1).strip(), pm.group(2)))
        methods.append((ret, name, plist, const))
    return methods


def pe_exports(path: pathlib.Path):
    data = path.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    opt = pe + 24
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    exp_rva = struct.unpack_from("<I", data, opt + 112)[0]  # PE32+: export directory
    secs = []
    for i in range(nsec):
        s = pe + 24 + opt_size + i * 40
        vsize, va, rsize, raw = struct.unpack_from("<IIII", data, s + 8)
        secs.append((va, max(vsize, rsize), raw))

    def off(rva):
        for va, size, raw in secs:
            if va <= rva < va + size:
                return rva - va + raw
        raise ValueError(rva)

    e = off(exp_rva)
    n_names = struct.unpack_from("<I", data, e + 24)[0]  # NumberOfNames
    names_rva = struct.unpack_from("<I", data, e + 32)[0]  # AddressOfNames
    names = []
    for i in range(n_names):
        r = struct.unpack_from("<I", data, off(names_rva) + 4 * i)[0]
        o = off(r)
        names.append(data[o:data.index(b"\0", o)].decode())
    return names


def gen_header(text: str) -> str:
    lines = [
        "// GENERATED by tools/gen_openvr_wrappers.py from third_party/openvr-0.9.12/headers/openvr.h. Do not edit by hand.",
        "#pragma once",
        "",
        "// Requires openvr.h 0.9.12 to be included first, and the declaration:",
        "//   void qvfr::TraceCall(int iface, int method);",
        "",
        "namespace qvfr { void TraceCall(int iface, int method); }",
        "",
        "namespace vr {",
        "namespace gen {",
        "",
    ]
    for idx, (cls, short, version) in enumerate(INTERFACES):
        methods = parse_methods(class_body(text, cls))
        lines.append(f"constexpr int k{short}Iface = {idx};")
        lines.append(f"constexpr int k{short}MethodCount = {len(methods)};")
        lines.append(f"inline const char* const k{short}Version = \"{version}\";")
        lines.append(f"inline const char* const k{short}MethodNames[] = {{")
        for _, name, _, _ in methods:
            lines.append(f"    \"{name}\",")
        lines.append("};")
        lines.append("")
        lines.append(f"class {short}WrapBase : public {cls} {{")
        lines.append("public:")
        lines.append(f"    explicit {short}WrapBase({cls}* real) : real_(real) {{}}")
        lines.append(f"    {cls}* Real() const {{ return real_; }}")
        lines.append("")
        for mi, (ret, name, plist, const) in enumerate(methods):
            sig = ", ".join(f"{t} {n}" for t, n in plist)
            args = ", ".join(n for _, n in plist)
            c = " const" if const else ""
            ret_kw = "" if ret == "void" else "return "
            lines.append(f"    {ret} {name}({sig}){c} override {{ qvfr::TraceCall({idx}, {mi}); "
                         f"{ret_kw}real_->{name}({args}); }}")
        lines.append("")
        lines.append("protected:")
        lines.append(f"    {cls}* real_;")
        lines.append("};")
        lines.append("")
    lines.append("constexpr int kIfaceCount = %d;" % len(INTERFACES))
    lines.append("")
    lines.append("}  // namespace gen")
    lines.append("}  // namespace vr")
    lines.append("")
    return "\n".join(lines)


def gen_forwards(exports) -> str:
    # Forwarding through linker directives (link.exe treats "name=module.name" in a .def file as an internal symbol).
    lines = [
        "// GENERATED by tools/gen_openvr_wrappers.py from the exports of openvr_api.dll 0.9.12. Do not edit by hand.",
        "// Functions in OWN_EXPORTS are exported by the proxy code (__declspec(dllexport)); the rest go to the original.",
    ]
    for name in exports:
        if name not in OWN_EXPORTS:
            lines.append(f'#pragma comment(linker, "/EXPORT:{name}={ORIG_MODULE}.{name}")')
    missing = OWN_EXPORTS - set(exports)
    if missing:
        sys.exit(f"OWN_EXPORTS not present in the original: {missing}")
    lines.append("")
    return "\n".join(lines)


def main():
    text = strip_comments(HEADER.read_text(encoding="utf-8", errors="replace"))
    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(gen_header(text), encoding="utf-8")
    exports = pe_exports(DLL)
    OUT_FWD.write_text(gen_forwards(exports), encoding="utf-8")
    print(f"{OUT_H.relative_to(ROOT)}: {len(INTERFACES)} interfaces")
    print(f"{OUT_FWD.relative_to(ROOT)}: {len(exports)} exports, {len(exports) - len(OWN_EXPORTS)} forwarded")


if __name__ == "__main__":
    main()
